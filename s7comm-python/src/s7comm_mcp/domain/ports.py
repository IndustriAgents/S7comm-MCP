from __future__ import annotations

from typing import Any, Protocol


class S7ClientPort(Protocol):
    config: Any

    def begin_shutdown(self) -> Any: ...

    def request_deadline(self, size: Any = ...) -> Any: ...

    def tool_call(self, cancel_scope: Any = ...) -> Any: ...

    async def ensure_connection(self) -> Any: ...

    async def close(self) -> Any: ...

    async def read_area(self, area: Any, start: Any, size: Any, db_number: Any = ...) -> Any: ...

    async def write_area(self, area: Any, start: Any, payload: Any, db_number: Any = ...) -> Any: ...

    async def write_bit(self, area: Any, byte_offset: Any, bit: Any, value: Any, db_number: Any = ...) -> Any: ...

    async def read_db(self, db_number: Any, start_offset: Any, size: Any) -> Any: ...

    async def write_db(self, db_number: Any, start_offset: Any, payload: Any) -> Any: ...

    async def read_plc_info(self) -> Any: ...

    async def read_cpu_state(self) -> Any: ...

    async def set_cpu_state(self, state: Any) -> Any: ...

    async def read_system_time(self) -> Any: ...

    async def read_szl(self, szl_id: Any, szl_index: Any) -> Any: ...

    def connection_status(self) -> Any: ...
